#!/usr/bin/env python3
"""Build workspace/files/scripts/package.json and marketplace/publish-exclude.txt from git. Run before every commit.

  python3 tools/build_manifest.py          write both files
  python3 tools/build_manifest.py --check  fail if they are out of date (use before pushing)

Settings per agent: tools/package.config.json
  {"agent": "smm", "name": "Sima", "repo": "iarbor04/ascn-smm-agent", "data_root": "files/smm",
   "addons": [{"file": "AGENTS.smm-addon.md", "into": "AGENTS.md"}],
   "legacy": {"knowledge/brand-kit.md": "profile/brand-kit.md"},
   "start": {"profile": "profile/brand-kit.md", "greeting": "...", "ready": "...", "failed": "...", "skill": "smm-onboarding"}}
Only files tracked by git are listed, so local leftovers never enter the package.
"""
import base64
import hashlib
import json
import subprocess
import sys
from datetime import date
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
WS = REPO / "workspace"
OUT = WS / "files" / "scripts" / "package.json"
EXCLUDE = REPO / "marketplace" / "publish-exclude.txt"
BUNDLE = REPO / "dist" / "package-bundle.json"
PLATFORM = ["AGENTS.md", "AUTOMATIONS.md", "USER.md", "MEMORY_POLICY.md", "rules/", "files/tool-output/"]


def tracked():
    out = subprocess.run(["git", "ls-files", "-z", "workspace"], cwd=REPO, capture_output=True, check=True).stdout
    return sorted(p[len("workspace/"):] for p in out.decode().split("\0") if p)


def build():
    cfg = json.loads((REPO / "tools" / "package.config.json").read_text(encoding="utf-8"))
    data_root = cfg["data_root"].rstrip("/")
    paths = [p for p in tracked() if p != "files/scripts/package.json"]
    leaked = [p for p in paths if p.startswith(data_root + "/")]
    if leaked:
        sys.exit(f"the data folder must not be in the package, move these to workspace/defaults/: {leaked}")
    files = {p: hashlib.sha256((WS / p).read_bytes()).hexdigest() for p in paths}
    content_id = hashlib.sha256(json.dumps(files, sort_keys=True).encode()).hexdigest()[:12]
    addons = []
    for a in cfg.get("addons") or []:
        marker = (WS / a["file"]).read_text(encoding="utf-8").splitlines()[0].strip()
        entry = {"file": a["file"], "into": a["into"], "marker": marker}
        if a.get("position") == "top":
            entry["position"] = "top"
            entry["end"] = (WS / a["file"]).read_text(encoding="utf-8").strip().splitlines()[-1].strip()
        addons.append(entry)
    exclude = [data_root + "/", "files/tool-output/", "files/scripts/__pycache__/"] + cfg.get("extra_exclude", [])
    manifest = {
        "agent": cfg["agent"], "name": cfg["name"], "repo": cfg["repo"], "version": f"{date.today().isoformat()}-{content_id}",
        "data_root": data_root, "defaults": "defaults",
        "skills": sorted({p.split("/")[1] for p in paths if p.startswith("skills/") and p.count("/") >= 2}),
        "addons": addons, "legacy": cfg.get("legacy") or {}, "refresh": cfg.get("refresh") or [], "platform": PLATFORM,
        "publish_exclude": exclude, "start": cfg.get("start") or {},
        "files": files,
    }
    note = ("# Paths to exclude when publishing this agent to the ASCN marketplace.\n"
            "# Generated by tools/build_manifest.py; do not edit by hand.\n"
            "# USER.md describes the workspace owner: exclude it too if the marketplace can exclude single files.\n")
    return manifest, note + "\n".join(exclude) + "\n"


def write_bundle(manifest):
    """Every package file (and package.json) base64-encoded with its sha256, in one file. The agent fetches it with a
    single GitHub integration call; the platform saves the large result to files/tool-output/, and package.py unpack
    writes the files byte for byte. No model retypes file contents."""
    files = {p: {"sha256": h, "b64": base64.b64encode((WS / p).read_bytes()).decode()} for p, h in manifest["files"].items()}
    raw = OUT.read_bytes()
    files["files/scripts/package.json"] = {"sha256": hashlib.sha256(raw).hexdigest(), "b64": base64.b64encode(raw).decode()}
    BUNDLE.parent.mkdir(exist_ok=True)
    BUNDLE.write_text(json.dumps({"repo": manifest["repo"], "version": manifest["version"], "files": files}, separators=(",", ":")) + "\n",
                      encoding="utf-8")


def main():
    manifest, exclude = build()
    old = json.loads(OUT.read_text(encoding="utf-8")) if OUT.exists() else {}
    same = {k: v for k, v in old.items() if k != "version"} == {k: v for k, v in manifest.items() if k != "version"}
    if "--check" in sys.argv:
        ok = same and EXCLUDE.exists() and EXCLUDE.read_text(encoding="utf-8") == exclude and BUNDLE.exists() and \
            json.loads(BUNDLE.read_text(encoding="utf-8")).get("version") == old.get("version")
        print("package.json is up to date" if ok else "package.json is out of date: run python3 tools/build_manifest.py")
        sys.exit(0 if ok else 1)
    if same:
        manifest["version"] = old.get("version", manifest["version"])
    OUT.write_text(json.dumps(manifest, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    EXCLUDE.write_text(exclude, encoding="utf-8")
    write_bundle(manifest)
    print(json.dumps({"ok": True, "version": manifest["version"], "files": len(manifest["files"]), "skills": len(manifest["skills"]),
                      "publish_exclude": manifest["publish_exclude"]}, ensure_ascii=False))


if __name__ == "__main__":
    main()
